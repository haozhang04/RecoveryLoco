# @ torch.jit.script
def quat_apply_yaw(quat, vec):
    quat_yaw = quat.clone().view(-1, 4)
    quat_yaw[:, :2] = 0.
    quat_yaw = normalize(quat_yaw)
    return quat_apply(quat_yaw, vec)

# @ torch.jit.script
def wrap_to_pi(angles):
    angles %= 2*torch.pi
    angles -= 2*torch.pi * (angles > torch.pi)
    return angles

# @ torch.jit.script
def torch_rand_sqrt_float(lower, upper, shape, device):
    # type: (float, float, Tuple[int, int], str) -> Tensor
    r = 2*torch.rand(*shape, device=device) - 1
    r = torch.where(r<0., -torch.sqrt(-r), torch.sqrt(r))
    r =  (r + 1.) / 2.
    return (upper - lower) * r + lower

def random_quat(U):
    u1 = U[:,0].unsqueeze(1)
    u2 = U[:,1].unsqueeze(1)
    u3 = U[:,2].unsqueeze(1)
    q1 = torch.sqrt(1-u1)*torch.sin(2*torch.pi*u2)
    q2 = torch.sqrt(1-u1)*torch.cos(2*torch.pi*u2)
    q3 = torch.sqrt(u1)*torch.sin(2*torch.pi*u3)
    q4 = torch.sqrt(u1)*torch.cos(2*torch.pi*u3)
    Q = torch.cat([q1,q2,q3,q4],dim=-1)
    return Q

# @ torch.jit.script
def quat_mul(a, b):
    assert a.shape == b.shape
    shape = a.shape
    a = a.reshape(-1, 4)
    b = b.reshape(-1, 4)
    x1, y1, z1, w1 = a[:, 0], a[:, 1], a[:, 2], a[:, 3]
    x2, y2, z2, w2 = b[:, 0], b[:, 1], b[:, 2], b[:, 3]
    ww = (z1 + x1) * (x2 + y2)
    yy = (w1 - y1) * (w2 + z2)
    zz = (w1 + y1) * (w2 - z2)
    xx = ww + yy + zz
    qq = 0.5 * (xx + (z1 - x1) * (x2 - y2))
    w = qq - ww + (z1 - y1) * (w2 - y2)
    x = qq - xx + (x1 + w1) * (x2 + w2)
    y = qq - yy + (w1 - x1) * (y2 + z2)
    z = qq - zz + (z1 + y1) * (w2 - x2)
    return torch.stack([x, y, z, w], dim=-1).view(shape) / torch.norm(torch.stack([x, y, z, w], dim=-1).view(shape), dim=-1, keepdim=True)

def sample_disjoint_intervals(env_ids, limit_bound, cfg_min, cfg_max, device):
    """Sample uniformly from [cfg_min, -limit_bound] U [limit_bound, cfg_max]."""
    width_neg = torch.clamp(-limit_bound - cfg_min, min=0.0)
    width_pos = torch.clamp(cfg_max - limit_bound, min=0.0)
    total_width = width_neg + width_pos + 1e-6
    u = torch.rand(len(env_ids), device=device) * total_width
    return torch.where(u < width_neg, cfg_min + u, cfg_max - width_pos + (u - width_neg))    